function encodeCp864(str) {
  const buf = Buffer.alloc(str.length);
  for (let i = 0; i < str.length; i++) {
    const char = str[i];
    if (cp864Map[char]) {
      buf[i] = cp864Map[char];
    } else {
      const code = char.charCodeAt(0);
      buf[i] = code < 256 ? code : 0x3f; // Fallback to '?'
    }
  }
  return buf;
}

